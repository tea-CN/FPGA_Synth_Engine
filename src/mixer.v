// 14 路 16 位有符号音频混音器（带饱和限幅，防止溢出削波）
module mixer(
    input  signed [15:0] w0, w1, w2, w3, w4, w5, w6,
    input  signed [15:0] s0, s1, s2, s3, s4, s5, s6,
    output signed [15:0] audio_out
);

    // 14 路相加，每路 16 位，需要扩展到 20 位才能保证绝对不溢出
    // (2^4 = 16 > 14，所以扩展 4 位符号位)
    wire signed [19:0] sum =
        {{4{w0[15]}}, w0} + {{4{w1[15]}}, w1} + {{4{w2[15]}}, w2} +
        {{4{w3[15]}}, w3} + {{4{w4[15]}}, w4} + {{4{w5[15]}}, w5} +
        {{4{w6[15]}}, w6} + 
        {{4{s0[15]}}, s0} + {{4{s1[15]}}, s1} + {{4{s2[15]}}, s2} +
        {{4{s3[15]}}, s3} + {{4{s4[15]}}, s4} + {{4{s5[15]}}, s5} +
        {{4{s6[15]}}, s6};

    // 饱和限幅：和超过 16 位有符号范围时，强行钳位在最大/最小值
    assign audio_out = (sum > 20'sd32767)  ? 16'sh7FFF :
                       (sum < -20'sd32768) ? 16'sh8000 :
                       sum[15:0];

endmodule